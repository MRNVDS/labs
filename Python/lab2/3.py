def number_to_words(n):
    units = ['', 'один', 'два', 'три', 'четыре', 'пять',
             'шесть', 'семь', 'восемь', 'девять']
    teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать',
             'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать',
             'восемнадцать', 'девятнадцать']
    tens = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
            'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто']
    hundreds = ['', 'сто', 'двести', 'триста', 'четыреста',
                'пятьсот', 'шестьсот', 'семьсот', 'восемьсот',
                'девятьсот']

    if n == 1000:
        return 'тысяча'

    words = ''
    if n >= 100:
        words += hundreds[n // 100] + ' '
        n %= 100
    if 10 <= n <= 19:
        words += teens[n - 10] + ' '
    else:
        if n >= 20:
            words += tens[n // 10] + ' '
            n %= 10
        if n > 0:
            words += units[n] + ' '
    return words.strip()

number = int(input("Введите число от 1 до 1000: "))

if 1 <= number <= 1000:
    print(number_to_words(number))
else:
    print("Число должно быть в диапазоне от 1 до 1000.")
